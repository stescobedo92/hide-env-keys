#[test]
fn materialize_adds_gitignore_entry_when_absent() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("FOO", "bar")]))
        .expect("materialize");

    let gitignore = std::fs::read_to_string(dir.path().join(".gitignore")).expect("read");
    assert!(
        gitignore.contains("/.env"),
        "expected /.env in:\n{gitignore}"
    );
}

#[test]
fn materialize_does_not_duplicate_gitignore_entry() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("FOO", "bar")]))
        .expect("first");
    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("FOO", "bar")]))
        .expect("second");

    let gitignore = std::fs::read_to_string(dir.path().join(".gitignore")).expect("read");
    let count = gitignore.lines().filter(|l| l.trim() == "/.env").count();
    assert_eq!(
        count, 1,
        "expected exactly one /.env entry, got:\n{gitignore}"
    );
}

#[test]
fn materialize_preserves_existing_gitignore_entries() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    std::fs::write(dir.path().join(".gitignore"), "target/\nnode_modules/\n").expect("seed");

    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("FOO", "bar")]))
        .expect("materialize");

    let gitignore = std::fs::read_to_string(dir.path().join(".gitignore")).expect("read");
    assert!(gitignore.contains("target/"), "original entries preserved");
    assert!(gitignore.contains("node_modules/"));
    assert!(gitignore.contains("/.env"));
}

#[test]
fn materialize_recognizes_basename_form_in_existing_gitignore() {
    // If the user already has `.env` (without leading slash), don't
    // append a redundant `/.env` entry.
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    std::fs::write(dir.path().join(".gitignore"), ".env\n").expect("seed");

    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("FOO", "bar")]))
        .expect("materialize");

    let gitignore = std::fs::read_to_string(dir.path().join(".gitignore")).expect("read");
    assert!(
        !gitignore.contains("/.env"),
        "should not add /.env on top of .env"
    );
}

#[test]
fn materialize_overwrites_existing_env_file() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    std::fs::write(&path, "OLD=stale\n").expect("seed");

    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("NEW", "fresh")]))
        .expect("materialize");

    let body = std::fs::read_to_string(&path).expect("read");
    assert!(body.contains("NEW=fresh"));
    assert!(!body.contains("OLD=stale"));
}

#[test]
fn materialize_leaves_no_tempfile_behind_on_success() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("FOO", "bar")]))
        .expect("materialize");

    let entries: Vec<_> = std::fs::read_dir(dir.path())
        .expect("read_dir")
        .filter_map(Result::ok)
        .map(|e| e.file_name())
        .collect();
    assert_eq!(
        entries.len(),
        2,
        "expected .env + .gitignore only, got: {entries:?}"
    );
}

#[cfg(unix)]
#[test]
fn materialize_sets_0o600_permissions_on_unix() {
    use std::os::unix::fs::PermissionsExt;
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("API_KEY", "sk-secret")]))
        .expect("materialize");

    let meta = std::fs::metadata(&path).expect("metadata");
    let mode = meta.permissions().mode() & 0o777;
    assert_eq!(
        mode, 0o600,
        ".env should be owner-only readable; got {mode:o}"
    );
}
