//! Integration tests for `EnvFileMaterializer`.

#![allow(clippy::expect_used)]

use std::collections::BTreeMap;

use evault_core::traits::Materializer;
use evault_materializer::EnvFileMaterializer;
use tempfile::TempDir;

fn env(entries: &[(&str, &str)]) -> BTreeMap<String, String> {
    entries
        .iter()
        .map(|(k, v)| ((*k).to_owned(), (*v).to_owned()))
        .collect()
}

#[test]
fn materialize_writes_alphabetized_keys_with_header() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    EnvFileMaterializer::new()
        .materialize(&path, &env(&[("ZED", "z"), ("ALPHA", "a"), ("BETA", "b")]))
        .expect("materialize");

    let body = std::fs::read_to_string(&path).expect("read");
    assert!(body.contains("# Generated by evault"));
    let kv_lines: Vec<&str> = body
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .collect();
    assert_eq!(kv_lines, vec!["ALPHA=a", "BETA=b", "ZED=z"]);
}

#[test]
fn materialize_quotes_values_with_special_chars() {
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    EnvFileMaterializer::new()
        .materialize(
            &path,
            &env(&[
                ("WITH_SPACE", "hello world"),
                ("WITH_EQUALS", "a=b"),
                ("WITH_QUOTE", "say \"hi\""),
                ("STARTS_WITH_HASH", "#not-a-comment"),
                ("EMPTY", ""),
            ]),
        )
        .expect("materialize");

    let body = std::fs::read_to_string(&path).expect("read");
    assert!(body.contains(r#"WITH_SPACE="hello world""#));
    assert!(body.contains(r#"WITH_EQUALS="a=b""#));
    assert!(body.contains(r#"WITH_QUOTE="say \"hi\"""#));
    assert!(body.contains("STARTS_WITH_HASH=\"#not-a-comment\""));
    assert!(body.contains(r#"EMPTY="""#));
}

#[test]
fn materialize_rejects_value_with_newline() {
    // Multi-line secrets (CRLF injection vector) MUST be rejected up-front.
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    let err = EnvFileMaterializer::new()
        .materialize(&path, &env(&[("TOKEN", "abc\nADMIN=true")]))
        .expect_err("should reject newline");
    let msg = format!("{err:?}");
    assert!(msg.contains("newline"), "expected newline mention: {msg}");
    assert!(msg.contains("TOKEN"), "expected key mention: {msg}");
    // CRITICAL: no part of the value text after the newline should appear
    // in the error string (would leak secret material).
    assert!(!msg.contains("ADMIN=true"), "value text leaked: {msg}");
    // No file should have been written.
    assert!(!path.exists(), ".env should not exist after rejection");
}

#[test]
fn materialize_rejects_value_with_carriage_return() {
    // CR alone (Windows-style line endings without LF) is also a vector.
    let dir = TempDir::new().expect("tmpdir");
    let path = dir.path().join(".env");
    let err = EnvFileMaterializer::new()
        .materialize(&path, &env(&[("TOKEN", "abc\rADMIN=true")]))
        .expect_err("should reject CR");
    let msg = format!("{err:?}");
    assert!(
        msg.contains("carriage return"),
        "expected CR mention: {msg}"
    );
    assert!(!path.exists());
}

